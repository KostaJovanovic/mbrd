// The source
// ---------------------------------------------------------------------------

/**
 * Everything under "## Releases", as a list of releases.
 *
 * The prose above that heading is the guide for whoever writes the next entry
 * and is not part of the changelog; splitting on it rather than on the first
 * `##` is what lets that guide use `##` headings of its own.
 */
function parseSource(text) {
  const cut = text.indexOf('\n## Releases\n');
  if (cut < 0) throw new Error('patch-notes.md has no "## Releases" heading');
  const body = text.slice(cut + '\n## Releases\n'.length);

  const releases = [];
  let current = null;
  for (const raw of body.split('\n')) {
    const line = raw.trimEnd();
    let m;
    if ((m = line.match(/^## (.+)$/))) {
      current = { name: m[1].trim(), version: '', date: '', parts: [{ head: null, bullets: [] }] };
      releases.push(current);
      continue;
    }
    if (!current) {
      if (line.trim()) throw new Error(`stray line before the first release: ${line}`);
      continue;
    }
    if ((m = line.match(/^version:\s*(.+)$/))) { current.version = m[1].trim(); continue; }
    if ((m = line.match(/^date:\s*(.+)$/))) { current.date = m[1].trim(); continue; }
    if ((m = line.match(/^### (.+)$/))) {
      current.parts.push({ head: m[1].trim(), bullets: [] });
      continue;
    }
    if ((m = line.match(/^- (.+)$/))) {
      let body = m[1].trim();
      let tag = null;
      const t = body.match(/^\[(new|fix|faster)\]\s*/);
      if (t) { tag = t[1]; body = body.slice(t[0].length); }
      current.parts.at(-1).bullets.push({ tag, body });
      continue;
    }
    if (line.trim()) throw new Error(`unreadable line in "${current.name}": ${line}`);
  }

  for (const r of releases) {
    if (!r.version) throw new Error(`"${r.name}" has no version:`);
    if (!r.date) throw new Error(`"${r.name}" has no date:`);
    if (!r.parts.some(p => p.bullets.length)) throw new Error(`"${r.name}" has no bullets`);
  }
  if (!releases.length) throw new Error('no releases found');
  return releases;
}

/** The tag word as it is printed, in both outputs. */
const TAG_WORD = { new: 'New', fix: 'Fix', faster: 'Faster' };

// ---------------------------------------------------------------------------
// Output one: the board
// ---------------------------------------------------------------------------

/**
 * One release as the Markdown a note card carries.
 *
 * meta.text is Markdown-flavoured - see note-model.ts, which is what the card
 * and the viewer both render - so the codename is the note's own heading and
 * the version and date are the line under it. The tag becomes bold text rather
 * than a chip: a note renders Markdown, and Markdown has no chips. The static
 * page draws the same tag as an outlined span, which is the one place the two
 * renderings of this source deliberately differ.
 */
function noteText(release) {
  const lines = [`# ${release.name}`, '', `${release.version} · ${release.date}`];
  for (const part of release.parts) {
    if (!part.bullets.length) continue;
    if (part.head) lines.push('', `## ${part.head}`);
    lines.push('');
    for (const b of part.bullets) {
      lines.push(`- ${b.tag ? `**${TAG_WORD[b.tag]}.** ` : ''}${b.body}`);
    }
  }
  return lines.join('\n');
}

/**
 * A note item, at the geometry the two layouts want.
 *
 * Desktop is a single column down the board, because a changelog is ordered and
 * a scatter would throw that away. Mobile carries the same order and the Feed
 * packs it into the masonry itself, so the heights here are only what the
 * canvas uses - the tile height on the Feed is measured from the words.
 *
 * The id is derived from the codename rather than random, and that is what
 * makes this file reproducible: running the generator twice with no edit in
 * between produces the same bytes, so a diff is a change to the notes and never
 * to the ids.
 */
const idOf = name => 'r-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const CARD_W = 460;
const CARD_GAP = 40;

function buildBoard(releases) {
  let y = 0;
  const items = releases.map((r, i) => {
    // Tall enough on the canvas to hold what it says: a line of the note sets
    // at roughly 22px at the card width, plus the head and the padding. The
    // Feed measures its own tiles and ignores this.
    const lines = r.parts.reduce((n, p) => n + p.bullets.reduce(
      (m, b) => m + Math.ceil((b.body.length + (b.tag ? 8 : 0)) / 52), p.head ? 2 : 0), 3);
    const h = Math.min(1400, Math.max(200, lines * 22 + 56));
    const item = {
      id: idOf(r.name),
      type: 'note',
      x: 0, y, w: CARD_W, h,
      rot: 0, z: releases.length - i,
      name: r.name,
      asset: null,
      meta: { text: noteText(r), tint: i === 0 ? 2 : 4 },
    };
    y += h + CARD_GAP;
    return item;
  });

  const geometry = items.map(i => ({ id: i.id, x: i.x, y: i.y, w: i.w, h: i.h, rot: 0, z: i.z }));
  return {
    title: 'Patch notes',
    view: { pan: { x: 0, y: 0 }, zoom: 1 },
    items,
    // Both layouts, so the board arrives knowing where its cards go in either -
    // the app opens this one in the Feed, but a visitor may switch to Canvas
    // from the sidebar like on any other board, and a board with no Desktop
    // geometry would arrange itself on the way.
    layouts: {
      desktop: { items: geometry, settings: {}, arrangement: 'free' },
      mobile: { items: geometry, settings: {}, arrangement: 'free' },
    },
    trash: [],
    connections: [],
    audioOrder: [],
  };
}

// ---------------------------------------------------------------------------
// The ZIP, written the way storage/zip.ts reads one
// ---------------------------------------------------------------------------

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/**
 * A ZIP, deflated where that is smaller.
 *
 * No timestamps anywhere: the DOS date and time fields are written as zero
 * rather than as now. A generated artifact that changes every time it is built
 * shows up as a diff in every commit that runs the generator, and the one thing
 * a committed build output has to be is a function of its source.
 */
function writeZip(entries) {
  const chunks = [];
  const central = [];
  let offset = 0;

  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, 'utf8');
    const deflated = deflateRawSync(data, { level: 9 });
    const store = deflated.length >= data.length;
    const payload = store ? data : deflated;
    const method = store ? 0 : 8;

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);        // version needed
    local.writeUInt16LE(0x0800, 6);    // UTF-8 names
    local.writeUInt16LE(method, 8);
    local.writeUInt32LE(crc32(data), 14);
    local.writeUInt32LE(payload.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    chunks.push(local, nameBytes, payload);

    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0);
    cd.writeUInt16LE(20, 4);           // version made by
    cd.writeUInt16LE(20, 6);           // version needed
    cd.writeUInt16LE(0x0800, 8);
    cd.writeUInt16LE(method, 10);
    cd.writeUInt32LE(crc32(data), 16);
    cd.writeUInt32LE(payload.length, 20);
    cd.writeUInt32LE(data.length, 24);
    cd.writeUInt16LE(nameBytes.length, 28);
    cd.writeUInt32LE(offset, 42);
    central.push(cd, nameBytes);

    offset += local.length + nameBytes.length + payload.length;
  }

  const cdBytes = Buffer.concat(central);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(entries.length, 8);
  eocd.writeUInt16LE(entries.length, 10);
  eocd.writeUInt32LE(cdBytes.length, 12);
  eocd.writeUInt32LE(offset, 16);

  return Buffer.concat([...chunks, cdBytes, eocd]);
}

/** The sidecar name packBoard() would have written for this note. */
function noteFile(item) {
  const first = String(item.meta.text).split('\n')[0];
  const slug = first.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48) || 'note';
  return `notes/${slug}--${item.id}.md`;
}

/** ...and its contents: first line as a heading, the rest as the body. */
function noteMarkdown(item) {
  const [title, ...rest] = String(item.meta.text).split('\n');
  const head = title.trim();
  const marker = /^#+\s/.test(head) ? '' : '# ';
  const body = rest.join('\n').trim();
  return (head ? marker + head + '\n' : '') + (body ? '\n' + body + '\n' : '');
}

function buildMbrd(board, version) {
  const json = obj => Buffer.from(JSON.stringify(obj, null, 2), 'utf8');
  const manifest = {
    format: 'mbrd',
    version: 1,
    app: 'mbrd ' + version,
    // No created/modified stamp, for the reason writeZip takes no timestamps:
    // this file is a function of its source and nothing else.
    title: board.title,
  };
  return writeZip([
    { name: 'manifest.json', data: json(manifest) },
    { name: 'board.json', data: json(board) },
    ...board.items.map(i => ({ name: noteFile(i), data: Buffer.from(noteMarkdown(i), 'utf8') })),
  ]);
}

