// Build the changelog, from research/patch-notes.md.
//
//   node tools/gen-patch-board.mjs
//
// Two outputs, one source, and neither is hand-editable:
//
//   web/assets/patch-notes.mbrd   the board itself - a real .mbrd, which is to
//                                 say a ZIP holding manifest.json, board.json
//                                 and one notes/*.md per release. The app opens
//                                 it through unpackBoard(), the same path a
//                                 dropped file takes, so nothing about /patch
//                                 is a special case inside the app.
//
//   web/patch.html                the page that serves it: index.html's shell
//                                 (so the app boots) with the changelog's own
//                                 <head>, and this prose inside <noscript> so a
//                                 crawler and a visitor with JavaScript off get
//                                 the words rather than an empty div.
//
// ── Why the shell is copied rather than written ──
//
// /patch has to boot the whole app: the menu button, the sidebar, the toolbar,
// the viewport, every stylesheet and the bundle. That markup lives in
// index.html and changes there; a second hand-kept copy would be wrong within a
// month. So the body is taken from index.html verbatim at build time and only
// the <head> is this page's own. It is the same bargain 404.html makes - a copy
// regenerated by a tool, with a test that fails when it drifts - except that
// this one is a copy of the body only, since the head is exactly what differs.
//
// ── Why the notes are ZIP entries and not just board.json ──
//
// Because that is what the format says a note is. packBoard() writes every
// sticky to notes/<slug>--<id>.md and unpackBoard() reads it back, with the
// sidecar outranking the copy in board.json. Writing the prose into both is
// what makes this file a board somebody could unzip and read, which is the
// second promise the format makes after "one file you can email".

import { readFileSync, writeFileSync } from 'node:fs';
import { deflateRawSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'research', 'patch-notes.md');
const SHELL = join(ROOT, 'web', 'index.html');
const OUT_BOARD = join(ROOT, 'web', 'assets', 'patch-notes.mbrd');
const OUT_PAGE = join(ROOT, 'web', 'patch.html');

const SITE = 'https://mbrd.valjdakosta.com';

