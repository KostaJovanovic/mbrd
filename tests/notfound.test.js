// web/404.html must be index.html byte for byte — the static host serves it
// for any miss. A drift means stale markup + confused service worker. save.bat
// remakes the copy; this test catches when it did not happen.
// The second test checks the wrangler.jsonc setting that makes Workers serve
// 404.html (not a bare 404 or a soft 200).

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { readFileSync } from 'node:fs';

import { ROOT, WEB } from './helpers.js';

test('web/404.html is index.html, byte for byte', () => {
  // Read as bytes, not text: a copy that differs only in its BOM or its line
  // endings is still a copy that was made by hand, and the next thing to go
  // that way is the markup.
  const index = readFileSync(join(WEB, 'index.html'));
  const notfound = readFileSync(join(WEB, '404.html'));

  assert.ok(notfound.equals(index),
    'web/404.html has drifted from web/index.html - it is a generated byte copy, remade by save.bat; do not hand-edit it');
});

test('the deploy config serves 404.html at a 404, not a bare miss or a soft one', () => {
  // Read as text and matched loosely. wrangler.jsonc is JSONC - comments, and
  // this file carries a lot of them - so this is a check that the setting is
  // present and says the right thing, not a parse.
  const cfg = readFileSync(join(ROOT, 'wrangler.jsonc'), 'utf8');

  assert.match(cfg, /"not_found_handling"\s*:\s*"404-page"/,
    'wrangler.jsonc must set assets.not_found_handling to "404-page" - without it a miss never reaches the app');
  assert.match(cfg, /"directory"\s*:\s*"\.\/web"/,
    'wrangler.jsonc must serve web/ - the 404 page is only found beside the rest of the app');
});
